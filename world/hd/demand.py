"""Ride requests for the high-detail cities.

San Francisco (data-calibrated)
    SFCTA "TNCs Today" gives Uber + Lyft pickups and drop-offs per Travel Analysis Zone
    (981 TAZ), day of week and hour (Nov-Dec 2016, trips entirely within SF). For each
    weekday-hour an origin-destination matrix is fitted by a doubly constrained gravity
    model (Furness / IPF): rows match the observed pickups, columns the drop-offs, with
    impedance exp(-d / L). This company carries `share` of it. Pickup and drop-off nodes
    are drawn inside each TAZ by land-use weight. Trips leaving SF (SFO and the bridges)
    are added on top, since SFCTA counts only internal trips.

Pune metro (purpose-based, no public trip data)
    Trips are generated by purpose flows (home->work, work->home, home->airport, ...),
    each with its own weekday / weekend time profile. Origins follow the origin purpose's
    node weights; destination zones follow a gravity choice on the destination purpose's
    weight and the typical travel time of that hour; then a node inside the zone.
    Each rider chooses a mode (bike taxi, auto-rickshaw, cab) by a logit on price, time,
    rain and luggage (airport): see MODES.

Every number marked ASSUMPTION is a knob of the simulated world.
"""

from __future__ import annotations

import json
from dataclasses import dataclass

import geopandas as gpd
import numpy as np
import pandas as pd
from scipy.spatial import cKDTree

from ..cities import City, DATA

SFCTA = DATA / "_external" / "sfcta"


# ---------------------------------------------------------------- modes

@dataclass(frozen=True)
class Mode:
    name: str
    base: float          # fare = max(min_fare, base + per_km km + per_min min) x surge
    per_km: float
    per_min: float
    min_fare: float
    speed_factor: float  # travel time multiplier on congested car times (bikes filter through traffic)
    capacity: int
    asc: float           # rider preference constant (logit)
    rain_penalty: float  # utility drop when raining (open vehicles)
    luggage_penalty: float  # utility drop for airport / station trips
    time_weight: float = 1.0  # discomfort per in-vehicle minute relative to a cab (open vehicles > 1)


# ASSUMPTION: Pune 2025 economy tariffs (INR) and preferences, tuned so that shares come
# out near bike 35% / auto 35% / cab 30% (ASCs fitted on a dry weekday); SF has one UberX-like product.
MODES = {
    "pune_hd": {
        "bike": Mode("bike", 15, 6.0, 0.5, 30, 0.75, 1, -1.50, 2.0, 2.5, 2.2),
        "auto": Mode("auto", 25, 11.0, 1.0, 40, 0.95, 3, 0.01, 0.6, 0.6, 1.5),
        "cab": Mode("cab", 40, 12.0, 1.5, 80, 1.00, 4, 0.0, 0.0, 0.0),
    },
    "sf_hd": {"cab": Mode("cab", 2.0, 0.85, 0.40, 8.0, 1.00, 4, 0.0, 0.0, 0.0)},
}
BETA_COST = {"pune_hd": -0.025, "sf_hd": -0.15}     # per currency unit (INR / USD)
BETA_TIME = -0.06                                   # per minute in vehicle


def mode_fare(m: Mode, km, minutes):
    return np.maximum(m.min_fare, m.base + m.per_km * km + m.per_min * minutes)


# ---------------------------------------------------------------- purpose flows (Pune)

def _profile(peaks, base=0.15):
    """24-hour weight from (hour, width, height) Gaussian bumps plus a floor."""
    h = np.arange(24) + 0.5
    p = np.full(24, base)
    for c, w, a in peaks:
        p += a * np.exp(-0.5 * ((h - c) / w) ** 2)
    return p / p.sum()


