# ASSUMPTION: multiplies every flow's destination decay; tuned so in-metro cab trips
# average about 30 min (Uber's Pune page: typical ride ~33 min)
DECAY_SCALE = 1.6


# ---------------------------------------------------------------- shared helpers

class Geography:
    """Node / zone lookups shared by both generators."""

    def __init__(self, city: City):
        d = city.data_dir
        self.city = city
        self.nodes = pd.read_parquet(d / "nodes.parquet")
        self.zones = pd.read_parquet(d / "zones.parquet")
        self.W = pd.read_parquet(d / "hd" / "node_weights.parquet")
        self.node_zone = self.nodes.zone.to_numpy()
        self.Z = len(self.zones)
        tdir = d / "traffic"
        self.zone_tt = np.load(tdir / "zone_tt_s.npy")              # (2, 24, Z, Z) seconds
        self.zone_dist = np.load(tdir / "zone_dist_m.npy")
        gw = pd.read_parquet(tdir / "gateways.parquet")
        pos = pd.Series(np.arange(len(self.nodes)), index=self.nodes.node_id)
        self.gw_pos = [int(pos.loc[n]) for n in gw.node_id]          # sorted by capacity

    def zone_nodes(self, weights: np.ndarray):
        """Per zone: (node indices, probabilities) for a node-weight vector."""
        out = {}
        for z in range(self.Z):
            idx = np.flatnonzero(self.node_zone == z)
            w = weights[idx]
            out[z] = (idx, w / w.sum() if w.sum() > 0 else np.full(len(idx), 1 / len(idx)))
        return out


# ---------------------------------------------------------------- San Francisco

class SFDemand:
    """SFCTA-calibrated OD per weekday-hour (doubly constrained gravity at TAZ level)."""

    L_KM = 4.0          # ASSUMPTION: impedance length, tuned so the mean trip is ~4.5 km (SFCTA ~3 mi)

    def __init__(self, geo: Geography):
        self.geo = geo
        stats = pd.DataFrame(json.loads((SFCTA / "tnc_trip_stats.json").read_text()))
        stats["hour"] = stats.time.str[:2].astype(int)
        taz = pd.DataFrame(json.loads((SFCTA / "taz_boundaries.json").read_text()))
        taz = gpd.GeoDataFrame(taz, geometry=gpd.GeoSeries.from_wkt(taz.geometry.map(_geojson_to_wkt)),
                               crs="EPSG:4326")
        taz = taz[taz.taz.isin(stats.taz.unique())].reset_index(drop=True)
        self.taz_ids = taz.taz.to_numpy()
        ti = {t: i for i, t in enumerate(self.taz_ids)}
        T = len(taz)
        self.P = np.zeros((7, 24, T))
        self.D = np.zeros((7, 24, T))
        k = stats.taz.map(ti).to_numpy()
        np.add.at(self.P, (stats.day_of_week, stats.hour, k), stats.pickups)
        np.add.at(self.D, (stats.day_of_week, stats.hour, k), stats.dropoffs)
        # node -> TAZ (nearest TAZ for nodes on the edge of the map)
        city = geo.city
        tz = taz.to_crs(city.utm_crs)
        pts = gpd.GeoDataFrame(geometry=gpd.points_from_xy(geo.nodes.x_m, geo.nodes.y_m), crs=city.utm_crs)
        j = gpd.sjoin(pts, tz[["geometry"]], predicate="within", how="left")
        j = j[~j.index.duplicated()]
        node_taz = j.index_right.to_numpy(dtype=float).copy()
        miss = np.isnan(node_taz)
        cen = tz.geometry.centroid
        if miss.any():
            _, nn = cKDTree(np.c_[cen.x, cen.y]).query(np.c_[geo.nodes.x_m[miss], geo.nodes.y_m[miss]])
            node_taz[miss] = nn
        self.node_taz = node_taz.astype(int)
        # within-TAZ node weights: activity + residents (pickup and drop-off spots)
        W = geo.W
        w = (W.home + W.work + W.shop + W.food_night + W.leisure + W.hub + 0.5 * (W.education + W.health)).to_numpy()
        self.taz_nodes = {}
        for t in range(T):
            idx = np.flatnonzero(self.node_taz == t)
            if len(idx):
                ww = w[idx]
                self.taz_nodes[t] = (idx, ww / ww.sum() if ww.sum() > 0 else np.full(len(idx), 1 / len(idx)))
        xy = np.c_[cen.x, cen.y] / 1000
        dist = np.sqrt(((xy[:, None] - xy[None]) ** 2).sum(-1)) * 1.3                 # road detour
        dist[np.diag_indices(T)] = 0.5 * np.sqrt(tz.area.to_numpy() / 1e6)
        self.dist_km = dist
        has = np.array([t in self.taz_nodes for t in range(T)])
        # TAZs with no road node (parks, water) cannot host a pickup: drop their counts
        self.P[..., ~has] = 0.0
        self.D[..., ~has] = 0.0
        self.F = np.exp(-dist / self.L_KM) * has[:, None] * has[None, :]
        self._od = {}

    def od(self, dow: int, hour: int) -> np.ndarray:
        """Furness-balanced OD probabilities for one weekday-hour (sums to 1)."""
        key = (dow, hour)
        if key not in self._od:
            p, q = self.P[dow, hour].copy(), self.D[dow, hour].copy()
            q *= p.sum() / max(q.sum(), 1e-9)
            a, b = np.ones_like(p), np.ones_like(q)
            for _ in range(40):
                a = p / np.maximum(self.F @ b, 1e-12)
                b = q / np.maximum(self.F.T @ a, 1e-12)
            T = a[:, None] * self.F * b[None, :]
            self._od[key] = T / T.sum()
        return self._od[key]

    def daily_total(self, dow: int) -> float:
        return float(self.P[dow].sum())


def _geojson_to_wkt(s):
    from shapely.geometry import shape
    return shape(json.loads(s)).wkt


# ---------------------------------------------------------------- generation

def generate(city: City, geo: Geography, date, customers: pd.DataFrame, cust_latent: pd.DataFrame,
             rng: np.random.Generator, sf: SFDemand | None = None, rain: float = 0.0,
             scale: float = 1.0) -> pd.DataFrame:
    """One day of requests. Columns: t_request, customer_id, origin/dest zone and node,
    external_dest, purpose, mode (rider's chosen product), patience."""
    date = pd.Timestamp(date)
    dow = date.weekday()
    weekend = dow >= 5
    m = city.market
    rows = []
    if city.key == "sf_hd":
        share = m.requests_per_day / sf.daily_total(2)               # calibrated on a Wednesday
        for h in range(24):
            lam = sf.P[dow, h].sum() * share * scale
            n = rng.poisson(lam)
            if not n:
                continue
            od = sf.od(dow, h).ravel()
            T = len(sf.taz_ids)
            pick = rng.choice(T * T, size=n, p=od)
            for oi, di in zip(pick // T, pick % T):
                o_idx, o_p = sf.taz_nodes[oi]
                d_idx, d_p = sf.taz_nodes[di]
                on = int(rng.choice(o_idx, p=o_p))
                dn = int(rng.choice(d_idx, p=d_p))
                if on == dn:
                    continue
                rows.append((h * 3600 + rng.uniform(0, 3600), on, dn, -1, "sfcta"))
    else:
        W = geo.W
        zw = {p: geo.zone_nodes(W[p].to_numpy()) for p in set(f[0] for f in FLOWS) | set(f[1] for f in FLOWS)}
        zmass = {p: np.array([W[p].to_numpy()[geo.node_zone == z].sum() for z in range(geo.Z)]) for p in zw}
        total = m.requests_per_day * (m.weekend_factor if weekend else 1.0) * scale
        dt = 1 if weekend else 0
        for o_p, d_p, sh_wd, sh_we, pk_wd, pk_we, decay in FLOWS:
            prof = _profile(pk_we if weekend else pk_wd)
            n_flow = total * (sh_we if weekend else sh_wd)
            for h in range(24):
                n = rng.poisson(n_flow * prof[h])
                if not n:
                    continue
                oz = rng.choice(geo.Z, size=n, p=zmass[o_p] / zmass[o_p].sum())
                tt = geo.zone_tt[dt, h] / 60.0
                for z in oz:
                    idx, p = zw[o_p][z]
                    on = int(rng.choice(idx, p=p))
                    if d_p == "airport":
                        dz_w = zmass["airport"]
                    else:
                        dz_w = zmass[d_p] * np.exp(-tt[z] / (decay * DECAY_SCALE))
                    dz = int(rng.choice(geo.Z, p=dz_w / dz_w.sum()))
                    idx, p = zw[d_p][dz]
                    dn = int(rng.choice(idx, p=p))
                    if dn == on:
                        continue
                    rows.append((h * 3600 + rng.uniform(0, 3600), on, dn, -1, f"{o_p}>{d_p}"))
    # intercity trips through gateways (both cities)
    n_ext = rng.poisson(len(rows) * m.intercity_share)
    ext_k = rng.choice(len(m.external), size=n_ext, p=[e.share for e in m.external])
    all_w = geo.W.home.to_numpy() + geo.W.work.to_numpy()
    for k in ext_k:
        h = int(rng.choice(24, p=_profile([(7.0, 2.0, 1.0), (18.0, 3.0, 1.0)])))
        on = int(rng.choice(len(all_w), p=all_w / all_w.sum()))
        rows.append((h * 3600 + rng.uniform(0, 3600), on, -1, int(k), "intercity"))

    req = pd.DataFrame(rows, columns=["t_request", "origin_node", "dest_node", "external_dest", "purpose"])
    req = req.sort_values("t_request").reset_index(drop=True)
    req["origin_zone"] = geo.node_zone[req.origin_node]
    req["dest_zone"] = np.where(req.dest_node >= 0, geo.node_zone[req.dest_node.clip(0)], -1)
    # rider: usually a resident near one end of the trip, weighted by riding frequency
    act = cust_latent.activity.to_numpy()
    all_pool = np.arange(len(act))
    pools = {z: g.index.to_numpy() for z, g in customers.groupby("home_zone")}
    cdfs = {z: np.cumsum(act[v]) for z, v in pools.items()}
    all_cdf = np.cumsum(act)
    cust = np.empty(len(req), np.int64)
    oz_a, dz_a = req.origin_zone.to_numpy(), req.dest_zone.to_numpy()
    u1, u2, u3 = rng.random(len(req)), rng.random(len(req)), rng.random(len(req))
    for i in range(len(req)):
        home = oz_a[i] if (dz_a[i] < 0 or u1[i] < 0.5) else dz_a[i]
        pool, cdf = pools.get(home), cdfs.get(home)
        if pool is None or u2[i] > 0.75:
            pool, cdf = all_pool, all_cdf
        cust[i] = pool[min(int(np.searchsorted(cdf, u3[i] * cdf[-1], side="right")), len(pool) - 1)]
    req.insert(0, "customer_id", cust)
    req["mode"] = choose_mode(city, geo, req, cust_latent, weekend, rain, rng)
    pat = cust_latent.patience_scale.to_numpy()[req.customer_id]
    req["patience_pre_s"] = 300.0 * pat * np.exp(0.3 * rng.standard_normal(len(req)))
    req["patience_post_s"] = 720.0 * pat * np.exp(0.3 * rng.standard_normal(len(req)))
    req.insert(0, "request_id", np.arange(len(req)))
    return req


def choose_mode(city, geo, req, cust_latent, weekend, rain, rng):
    """Multinomial logit over the city's products on typical fare and time."""
    modes = MODES[city.key]
    names = list(modes)
    if len(names) == 1:
        return np.array(names * len(req))
    dt = 1 if weekend else 0
    h = (req.t_request // 3600).astype(int).clip(0, 23).to_numpy()
    oz = req.origin_zone.to_numpy()
    dz = np.where(req.dest_zone >= 0, req.dest_zone, oz)
    km = np.maximum(geo.zone_dist[dt, h, oz, dz], 800) / 1000 + np.where(req.external_dest >= 0, 12.0, 0.0)
    mins = np.maximum(geo.zone_tt[dt, h, oz, dz], 120) / 60 + np.where(req.external_dest >= 0, 18.0, 0.0)
    luggage = req.purpose.str.contains("airport|hub|intercity").to_numpy()
    sens = cust_latent.price_sensitivity.to_numpy()[req.customer_id] if "price_sensitivity" in cust_latent else 1.0
    U = []
    for n in names:
        mo = modes[n]
        t = mins * mo.speed_factor
        f = mode_fare(mo, km, t)
        U.append(mo.asc + BETA_COST[city.key] * sens * f + BETA_TIME * mo.time_weight * t
                 - mo.rain_penalty * rain - mo.luggage_penalty * luggage - (0.08 * np.maximum(km - 10, 0) if n == "bike" else 0))
    U = np.stack(U, 1)
    P = np.exp(U - U.max(1, keepdims=True))
    P /= P.sum(1, keepdims=True)
    u = rng.random(len(req))[:, None]
    return np.array(names)[(P.cumsum(1) < u).sum(1)]
